#!/usr/bin/env python3
"""Generate ``force_block.vh`` to remove gate-level X-pessimism in hardened sim.

A hardened fabric powers up all-X (OpenROAD resynthesises FABulous's X-optimistic
cells into X-pessimistic gates), and the X never clears on its own. This script
emits ``force_block.vh`` (compiled in with ``-DGL_SIM``) with two one-shot actions
fired at ``config_done``:

1. ``$deposit 0`` on every still-X fabric net -- breaks the combinational X web.
2. A per-flop state clear (a net deposit cannot reach a flop, which re-drives its
   own ``Q``). It is PDK-adaptive, because OpenROAD maps the FABulous DFF to a
   different cell per PDK: a reset-pin pulse where the mapped cell has an async
   reset (IHP ``sg13g2_dfrbpq``, ``RESET_B``), a ``$deposit(Q, 0)`` where it does
   not (sky130 ``dfxtp``, gf180 ``dffq``, ICS55 ``DFFQX1H7L``).

Both actions are **X-only** (gated on the target still being X), so they only add
definedness where the design left X and can never overwrite a configured value or
hide a bug -- a wrong value still mismatches the golden reference.

The netlist is either hierarchical (``--tile-dir`` given: tile macros
instantiated by the fabric top, flops read from each tile netlist) or flat
(``--tile-dir`` omitted: every cell lives in ``--efpga`` itself).

``--dump-cell`` (flat netlists only) additionally writes every instance of that
cell with its ``Q`` to ``--dump-out`` at the trigger, before any X-init, so an X
left by configuration is recorded as ``x`` rather than as the deposited 0. Names
are the netlist identifiers without the escape backslash.

Implication: a future fabric with a power-on INIT bit staged in config memory but
not yet reflected in ``Q`` would be defaulted to 0 by the flop clear; that case
needs the clear to target the configured INIT value instead.

Usage
-----
    python3 gen_gl_xinit.py \
        --efpga ../Fabric/macro/final_views/nl/eFPGA.nl.v \
        --tile-dir ../Tile \
        --pdk ihp-sg13g2 \
        --top-inst top_i.eFPGA_inst \
        --trigger config_done \
        --out force_block.vh
"""

from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass
from pathlib import Path


@dataclass(frozen=True)
class FlopPins:
    """Flip-flop pin names of one PDK's standard cells."""

    clock: str
    reset: str


# ``clock`` is the edge-clock pin that tells a flop from a config latch.
# ``reset`` is the active-low async reset; presence is decided per instance: IHP
# maps to a resettable cell (sg13g2_dfrbpq, RESET_B); sky130 / gf180 / ICS55 map
# to resetless DFFs, cleared by depositing Q instead.
_FLOP_PINS_BY_PDK: dict[str, FlopPins] = {
    "ihp-sg13g2": FlopPins(clock="CLK", reset="RESET_B"),
    "sky130A": FlopPins(clock="CLK", reset="RESET_B"),
    "gf180mcuD": FlopPins(clock="CLK", reset="RN"),
    "ics55": FlopPins(clock="CK", reset="RN"),
}

# force_block.vh skeleton. {net_deposits}, {flop_clears} and {releases} are
# spliced in as one generated line per net / flop; {summary} is the closing
# $display. {cell_dump} is empty unless --dump-cell is given; it runs before
# the X-init so it records configuration, not deposits. Every generated action
# is gated on the target still being X, so the scrub only adds definedness and
# never overwrites a configured value.
_BLOCK_TEMPLATE = """\
// AUTO-GENERATED by gen_gl_xinit.py -- do not edit by hand.
// Gate-level X-pessimism removal for hardened-fabric sim ({pdk}).
initial begin : gl_xinit
{cell_dump_decl}    wait ({trigger} === 1'b1);  // configuration upload complete
{cell_dump}
    #1;
    // 1) break the unused-routing combinational X web. X-only: a net
    //    the configuration already drives to a constant is left alone,
    //    so a real configured value is never overwritten with 0.
{net_deposits}
    // 2) clear flop state X (a net deposit cannot reach it -- the flop
    //    re-drives its own Q). X-only: a flop already holding a defined
    //    value (e.g. a future INIT-bit power-on value) is left alone.
{flop_clears}
    #1;
{releases}
{summary}
end
"""


def collect_efpga_nets(efpga_text: str) -> list[str]:
    """Return every net declared at the fabric top level.

    Parameters
    ----------
    efpga_text : str
        Contents of the fabric netlist (``eFPGA.nl.v``).

    Returns
    -------
    list[str]
        Net names, range prefixes stripped; escaped identifiers keep their
        leading backslash.
    """
    names: list[str] = []
    for line in efpga_text.splitlines():
        s = line.strip()
        if not s.startswith("wire "):
            continue
        body = s[len("wire ") :].rstrip(";").strip()
        for tok in body.split(","):
            tok = tok.strip()
            if not tok:
                continue
            tok = re.sub(r"^\[[^\]]*\]\s*", "", tok)  # drop range prefix
            names.append(tok)
    return names


# A gate-level cell instantiation: ``CELL inst ( .PIN(net), ... );``. Net names
# (including escaped identifiers) never contain ``)`` or ``;``, so the body runs
# to the first ``);``.
_INST_RE = re.compile(r"\b\w+\s+\S+\s*\((.*?)\)\s*;", re.DOTALL)


def collect_netlist_flops(
    netlist_text: str, pins: FlopPins
) -> list[tuple[str, str | None]]:
    """Return one netlist's flip-flops as ``(Q net, reset net | None)`` pairs.

    A flip-flop is any cell instantiation carrying both a ``Q`` output and the
    PDK edge-clock pin. The clock-pin requirement is what isolates the
    edge-triggered user flops from the gate-enabled configuration-memory latches
    (``latq`` / ``dlxtp`` / ``LATHX1H7L``), which also expose a ``Q`` but are
    enabled by ``E`` / ``GATE`` / ``G`` and have no clock; it stays
    std-cell-name agnostic. If the flop also carries the PDK async reset pin its
    reset net is recorded, otherwise the pair holds ``None`` -- the two get
    different X-init treatment (a reset pulse vs a ``Q`` deposit). Either way the
    action is gated on the flop's own ``Q`` being X, so a flop already holding a
    defined value is left alone.

    Parameters
    ----------
    netlist_text : str
        Contents of one gate-level netlist.
    pins : FlopPins
        The PDK's flop clock and async reset pin names. A flop whose
        instantiation lacks the reset pin is paired with ``None``.

    Returns
    -------
    list[tuple[str, str | None]]
        ``(Q net, reset net | None)``, one entry per flop instance.
    """
    rpin = re.compile(rf"\.{re.escape(pins.reset)}\(\s*(.*?)\s*\)")
    qpin = re.compile(r"\.Q\(\s*(.*?)\s*\)")
    has_clk = re.compile(rf"\.{re.escape(pins.clock)}\(")
    pairs: list[tuple[str, str | None]] = []
    for body in _INST_RE.findall(netlist_text):
        qm = qpin.search(body)
        if not qm or not has_clk.search(body):
            continue
        rm = rpin.search(body)
        reset_net = rm.group(1).strip() if rm else None
        pairs.append((qm.group(1).strip(), reset_net))
    return pairs


def collect_flops(
    tile_dir: Path, pins: FlopPins
) -> dict[str, list[tuple[str, str | None]]]:
    """Map each tile type to its flip-flops' ``(Q net, reset net | None)`` pairs.

    Parameters
    ----------
    tile_dir : Path
        The project ``Tile`` directory.
    pins : FlopPins
        The PDK's flop clock and async reset pin names.

    Returns
    -------
    dict[str, list[tuple[str, str | None]]]
        Tile type (the ``Tile/<type>`` directory name) -> list of
        ``(Q net, reset net | None)``, one entry per flop instance.
    """
    out: dict[str, list[tuple[str, str | None]]] = {}
    for nl in sorted(tile_dir.glob("*/macro/final_views/nl/*.nl.v")):
        pairs = collect_netlist_flops(netlist_text=nl.read_text(), pins=pins)
        if pairs:
            out[nl.parents[3].name] = pairs
    return out


def collect_cell_instances(netlist_text: str, cell: str) -> list[str]:
    """Return the instance names of every ``cell`` instantiation in a netlist.

    Parameters
    ----------
    netlist_text : str
        Contents of one gate-level netlist.
    cell : str
        Standard-cell master name.

    Returns
    -------
    list[str]
        Instance names as written; escaped identifiers keep their backslash.
    """
    inst_re = re.compile(rf"^\s*{re.escape(cell)}\s+(\S+)\s*\(", re.MULTILINE)
    return inst_re.findall(netlist_text)


def collect_flop_tile_instances(
    efpga_text: str, types: list[str]
) -> list[tuple[str, str]]:
    """Return ``(tile_type, instance_name)`` for every flop-bearing tile instance.

    Parameters
    ----------
    efpga_text : str
        Contents of the fabric netlist (``eFPGA.nl.v``).
    types : list[str]
        Tile types known to contain flip-flops.

    Returns
    -------
    list[tuple[str, str]]
        One entry per matching tile instantiation. Empty when ``types`` is
        empty (an empty alternation would otherwise match arbitrary lines).
    """
    if not types:
        return []
    inst_re = re.compile(r"^\s*({types})\s+(\S+)\s+\(".format(types="|".join(types)))
    found: list[tuple[str, str]] = []
    for line in efpga_text.splitlines():
        m = inst_re.match(line)
        if m:
            found.append((m.group(1), m.group(2)))
    return found


def hier_ref(top_inst: str, *parts: str) -> str:
    """Build a hierarchical reference below ``top_inst``, preserving escapes.

    The reference is ``top_inst`` followed by ``parts`` joined with ``.`` -- e.g.
    ``hier_ref(top, net)`` for a top-level net, ``hier_ref(top, inst, net)`` for a
    tile-internal one. A Verilog escaped identifier (leading backslash) must be
    terminated by whitespace, so every escaped segment keeps a trailing space.

    Parameters
    ----------
    top_inst : str
        Hierarchical path to the gate-level fabric top level instance.
    *parts : str
        Net/instance names below ``top_inst``, outermost first.

    Returns
    -------
    str
        ``<top_inst>.<part>...``; each escaped segment keeps its trailing
        space.
    """
    return ".".join((top_inst, *(f"{p} " if p.startswith("\\") else p for p in parts)))


def main() -> None:
    """Emit the X-init include consumed by the gate-level testbench."""
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--efpga", required=True, type=Path)
    ap.add_argument(
        "--tile-dir",
        type=Path,
        help="project Tile directory of a hierarchical netlist; omit when "
        "--efpga is flat",
    )
    ap.add_argument(
        "--pdk",
        required=True,
        choices=sorted(_FLOP_PINS_BY_PDK),
        help="PDK whose flip-flop async reset pin should be pulsed (when its "
        "mapped flop has one; resetless flops are cleared by depositing Q)",
    )
    ap.add_argument(
        "--top-inst",
        default="top_i.eFPGA_inst",
        help="hierarchical path to the gate-level fabric top level instance",
    )
    ap.add_argument(
        "--trigger",
        default="config_done",
        help="testbench signal that is 1 once config upload finished",
    )
    ap.add_argument("--out", required=True, type=Path)
    ap.add_argument(
        "--dump-cell",
        help="flat netlists only: record every instance of this cell and its Q "
        "at the trigger, before the X-init",
    )
    ap.add_argument(
        "--dump-out",
        type=Path,
        help="file the simulator writes the --dump-cell records to",
    )
    args = ap.parse_args()
    if (args.dump_cell is None) != (args.dump_out is None):
        ap.error("--dump-cell and --dump-out go together")
    if args.dump_cell is not None and args.tile_dir is not None:
        ap.error("--dump-cell needs a flat netlist; drop --tile-dir")

    pins = _FLOP_PINS_BY_PDK[args.pdk]

    efpga_text = args.efpga.read_text()
    nets = collect_efpga_nets(efpga_text)

    # (Q net, reset net | None) paths below --top-inst, one per flop instance.
    flop_paths: list[tuple[tuple[str, ...], tuple[str, ...] | None]] = []
    if args.tile_dir is None:
        for qnet, rnet in collect_netlist_flops(netlist_text=efpga_text, pins=pins):
            flop_paths.append(((qnet,), None if rnet is None else (rnet,)))
        n_flop_scopes = 1
    else:
        flops = collect_flops(args.tile_dir, pins)
        instances = collect_flop_tile_instances(efpga_text, sorted(flops))
        for ttype, inst in instances:
            for qnet, rnet in flops.get(ttype, []):
                flop_paths.append(
                    ((inst, qnet), None if rnet is None else (inst, rnet))
                )
        n_flop_scopes = len(instances)

    # Split flops by how their state X is cleared: a reset pulse where the mapped
    # cell has an async reset pin, a Q deposit where it does not.
    reset_flops: list[tuple[str, str]] = []  # (Q net ref, reset net ref)
    deposit_flops: list[str] = []  # Q net ref
    for qpath, rpath in flop_paths:
        qref = hier_ref(args.top_inst, *qpath)
        if rpath is not None:
            reset_flops.append((qref, hier_ref(args.top_inst, *rpath)))
        else:
            deposit_flops.append(qref)

    cell_dump: list[str] = []
    if args.dump_cell is not None:
        dumped = collect_cell_instances(netlist_text=efpga_text, cell=args.dump_cell)
        if not dumped:
            ap.error(f"no {args.dump_cell} instance in {args.efpga}")
        cell_dump.append(f"    // 0) record every {args.dump_cell} Q as configured.")
        cell_dump.append(f'    gl_dump_fd = $fopen("{args.dump_out}", "w");')
        cell_dump.append(
            f'    if (gl_dump_fd == 0) $fatal(1, "cannot open {args.dump_out}");'
        )
        for inst in dumped:
            ref = hier_ref(args.top_inst, inst, "Q")
            name = inst.removeprefix("\\")
            cell_dump.append(f'    $fdisplay(gl_dump_fd, "{name} %b", {ref});')
        cell_dump.append("    $fclose(gl_dump_fd);")
        cell_dump.append(
            f'    $display("[gl_xinit] dumped {len(dumped)} {args.dump_cell} Q to '
            f'{args.dump_out} @ %0t", $time);'
        )

    # Build each dynamic block as a list of lines; _BLOCK_TEMPLATE lays them out.
    net_deposits: list[str] = []
    for n in nets:
        ref = hier_ref(args.top_inst, n)
        net_deposits.append(f"    if ({ref} === 1'bx) $deposit({ref}, 1'b0);")

    flop_clears: list[str] = []
    if reset_flops:
        flop_clears.append(
            f"    //    2a) async-reset pulse ({pins.reset}, active-low)."
        )
        for qref, rref in reset_flops:
            flop_clears.append(f"    if ({qref} === 1'bx) force {rref}= 1'b0;")
    if deposit_flops:
        flop_clears.append("    //    2b) resetless flops: seed Q directly.")
        for qref in deposit_flops:
            flop_clears.append(f"    if ({qref} === 1'bx) $deposit({qref}, 1'b0);")

    releases = [f"    release {rref};" for _qref, rref in reset_flops]

    summary = (
        '    $display("[gl_xinit] %0d deposits, %0d flop resets, %0d flop deposits'
        f' @ %0t", {len(nets)}, {len(reset_flops)}, {len(deposit_flops)}, $time);'
    )

    args.out.write_text(
        _BLOCK_TEMPLATE.format(
            pdk=args.pdk,
            cell_dump_decl="    integer gl_dump_fd;\n" if cell_dump else "",
            cell_dump="\n".join(cell_dump),
            trigger=args.trigger,
            net_deposits="\n".join(net_deposits),
            flop_clears="\n".join(flop_clears),
            releases="\n".join(releases),
            summary=summary,
        )
    )
    sys.stderr.write(
        f"wrote {args.out}: {len(nets)} net deposits, {len(reset_flops)} flop "
        f"reset pulses, {len(deposit_flops)} flop Q deposits "
        f"({n_flop_scopes} flop scopes, reset pin {pins.reset})\n"
    )


if __name__ == "__main__":
    main()
