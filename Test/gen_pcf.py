"""Write the PCF that places pad[i] on the IOBUF eFPGA_top exposes as A_*_top[i].

Yosys elaborates the variant's eFPGA_top with eFPGA as a blackbox, and the pad
index of each Tile_X<x>Y<y>_<bel>_{IN,EN,OUT}_top port of the eFPGA instance is
read from the top-level bit it connects to. All three ports of one IOBUF must
land on the same index, so a miswired top fails here rather than in the field.

    python3 Test/gen_pcf.py fabrics/nobram fabrics/nobram/user_design/pads.pcf
"""

import csv
import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PORT = re.compile(r"Tile_X(\d+)Y(\d+)_([A-Z])_(IN|EN|OUT)_top")


def grid(variant: Path) -> list[list[str]]:
    rows: list[list[str]] = []
    inside = False
    with (variant / "fabric.csv").open() as f:
        for row in csv.reader(f):
            head = row[0].strip() if row else ""
            if head == "FabricBegin":
                inside = True
            elif head == "FabricEnd":
                inside = False
            elif inside:
                rows.append([c.strip() for c in row])
    return rows


def pad_bels(variant: Path) -> dict[int, tuple[int, int, str]]:
    """Map each pad index to the (x, y, bel) of its IOBUF."""
    with tempfile.TemporaryDirectory() as tmp:
        out = Path(tmp) / "top.json"
        script = Path(tmp) / "top.ys"
        script.write_text(
            f"read_verilog -lib {variant / 'Fabric' / 'eFPGA.v'}\n"
            f"read_verilog -lib {' '.join(str(ROOT / 'Fabric' / n) for n in ('config_frontend.v', 'config_UART.v', 'bitbang.v', 'config_spi.v'))}\n"
            f"read_verilog -sv -lib {ROOT / 'Fabric' / 'fabric_config.sv'}\n"
            f"read_verilog {variant / 'Fabric' / 'eFPGA_top.v'}\n"
            f"hierarchy -top eFPGA_top\nwrite_json {out}\n"
        )
        subprocess.run(["yosys", "-q", "-s", str(script)], check=True)
        top = json.loads(out.read_text())["modules"]["eFPGA_top"]
    bit_index = {b: i for p in top["ports"].values() for i, b in enumerate(p["bits"])}
    fabrics = [c for c in top["cells"].values() if c["type"] == "eFPGA"]
    if len(fabrics) != 1:
        raise ValueError(f"expected one eFPGA instance in eFPGA_top, found {len(fabrics)}")
    pads: dict[int, set[tuple[int, int, str]]] = {}
    for port, bits in fabrics[0]["connections"].items():
        m = PORT.fullmatch(port)
        if m is None:
            continue
        if len(bits) != 1 or bits[0] not in bit_index:
            raise ValueError(f"{port} does not reach a single eFPGA_top port bit")
        pads.setdefault(bit_index[bits[0]], set()).add((int(m[1]), int(m[2]), m[3]))
    for i, locs in pads.items():
        if len(locs) != 1:
            raise ValueError(f"pad {i}: IN, EN and OUT come from different BELs {sorted(locs)}")
    return {i: next(iter(locs)) for i, locs in sorted(pads.items())}


def main(variant: Path, out: Path) -> None:
    tiles = grid(variant)
    lines = [
        "# Generated by Test/gen_pcf.py from eFPGA_top; do not edit by hand.",
        "# pad[i] is the IOBUF behind A_IN_top[i], A_EN_top[i] and A_OUT_top[i].",
        "# Rename pad[i] to a port of your own top to place that port on pad i.",
    ]
    for i, (x, y, bel) in pad_bels(variant).items():
        lines.append(f"set_io pad[{i}] X{x}Y{y}/{bel}  # {tiles[y][x]}")
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out}, {len(lines) - 3} pads")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    main(Path(sys.argv[1]).resolve(), Path(sys.argv[2]))
